"""Real dispatch, private SQLite database, boundaries and durable receipts."""
import json,os,sys,tempfile
from pathlib import Path
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'port/server'))
os.environ['NR_ENABLE_TUTORIAL']='0'
with tempfile.TemporaryDirectory(prefix='quick-upgrades-',dir=root/'build') as folder:
    os.environ['NR_ACCOUNTS_DIR']=folder
    import local_server as server
    import equipment_local as equipment
    import recruitment_local as heroes
    import hero_level_local as levels
    import hero_stats_local as stats
    db=server.BANCO
    try:
        account=db.criar_conta('quick_test','Temporary123!')['id']
        server._sessao_conexao['token']=db.abrir_sessao(account)
        uid=db.perfil(account)['user_id'];server.resposta_login_init('1','')
        ship,mould=heroes.all_owned(db,account)[0]
        def request(command,*args,seq='2'):
            return server.despacha('\r\n'.join(map(str,[seq,command,uid,*args])))
        def equip(mode,target,key,slot=1,owner=ship,seq='2'):
            return request('equipment_escalate',owner,0,slot,mode,target,key,seq=seq)
        def silver():return db._conn.execute('SELECT silver FROM local_campaign WHERE conta_id=?',(account,)).fetchone()[0]
        def balance(value):
            with db._conn:db._conn.execute('INSERT OR REPLACE INTO local_campaign VALUES (?,100,?)',(account,value))
        table=equipment.rows(mould,1);balance(100000000)
        (root/'build/quick-before-login.txt').write_text(server.resposta_login_init('1',''),encoding='utf8')
        base=stats.effective(db,account,ship,mould)
        first=equip(0,-1,'single');assert first.startswith('2 equipment_escalate 0 '),first
        assert equipment.levels(db,account,ship)==[2,1,1,1,1,1]
        assert silver()==100000000-int(table[1][2])
        after=silver();assert equip(0,-1,'single',seq='9').split(' ',1)[1]==first.split(' ',1)[1]
        assert silver()==after
        assert ' -1 ' in equip(1,10,'single')
        quick=equip(1,10,'to-ten');assert quick.startswith('2 equipment_escalate 0 '),quick
        assert equipment.levels(db,account,ship)[0]==10
        assert silver()==100000000-sum(int(table[i][2]) for i in range(1,10))
        assert stats.effective(db,account,ship,mould)!=base
        after=silver();assert ' -1 ' in equip(1,15,'missing-material')
        assert silver()==after and equipment.levels(db,account,ship)[0]==10
        item,count=int(table[10][3]),int(table[10][4])
        with db._conn:db._conn.execute('INSERT INTO local_inventory VALUES (?,?,?,?)',(account,item,account*1000000+item,count))
        promoted=equip(0,-1,'promotion');assert promoted.startswith('2 equipment_escalate 0 '),promoted
        assert equipment.levels(db,account,ship)[0]==10 and equipment.qualities(db,account,ship)[0]==1
        assert silver()==after-int(table[10][13])
        assert db._conn.execute('SELECT quantity FROM local_inventory WHERE conta_id=? AND mould=?',(account,item)).fetchone()[0]==0
        before=silver();bulk=equip(1,15,'to-fifteen');assert bulk.startswith('2 equipment_escalate 0 '),bulk
        assert equipment.levels(db,account,ship)[0]==15
        assert silver()==before-sum(int(table[i][2]) for i in range(10,15))
        # Partial progress consumes only affordable steps; a completely blocked request is refused.
        balance(int(equipment.rows(mould,2)[1][2])*2)
        partial=equip(1,10,'partial',slot=2);assert partial.startswith('2 equipment_escalate 0 '),partial
        assert equipment.levels(db,account,ship)[1]==3 and silver()==0
        assert ' -1 ' in equip(0,-1,'no-silver',slot=2)
        balance(100000000)
        assert equip(1,-1,'ordinary-quick',slot=3).startswith('2 equipment_escalate 0 ')
        assert equipment.levels(db,account,ship)[2]==10
        before=silver();assert ' -1 ' in equip(1,-1,'ordinary-boundary',slot=3);assert silver()==before
        for args in [(1,999,'bad-target'),(1,20,'bad-slot',7),(1,20,'foreign',1,ship+999999)]:assert ' -1 ' in equip(*args)
        balance(100000000)
        # Account level at a promotion is checked separately for each slot.
        limited=next((n,r) for n,r in table.items() if r[15]!='-1' and n+1 in table)
        n,row=limited
        with db._conn:
            db._conn.execute('INSERT OR REPLACE INTO local_equipment_level VALUES (?,?,?,?,?)',(account,ship,1,n,int(row[12])))
            db._conn.execute('UPDATE local_campaign SET grade=1 WHERE conta_id=?',(account,))
        before=silver();assert 'nivel_do_jogador_insuficiente' in equip(1,n+1,'account-limit');assert silver()==before
        with db._conn:db._conn.execute('INSERT OR REPLACE INTO local_equipment_level VALUES (?,?,?,?,?)',(account,ship,4,120,22))
        assert ' -1 ' in equip(0,-1,'equipment-cap',slot=4)
        # Ninja fast upgrade supplies exactly the fields generated by SmAutoUpgrade.
        balance(100000000)
        foods=[]
        for row in levels.data.tabela('prop_mould.txt').values():
            food=levels.data.tabela('ship_mould.txt').get(row[39])
            if food and int(food[54])>0:foods.append((int(row[0]),int(food[54])))
        prop,value=foods[0];instance=account*1000000+prop
        with db._conn:db._conn.execute('INSERT OR REPLACE INTO local_inventory VALUES (?,?,?,?)',(account,prop,instance,10000))
        food_text=str(instance)+':10000';before=silver()
        (root/'build/quick-ninja-before-login.txt').write_text(server.resposta_login_init('1',''),encoding='utf8')
        reply=request('ship_escalate',0,ship,food_text,10,'ninja-fast');assert reply.startswith('2 ship_escalate 0 '),reply
        assert levels.state(db,account,ship,mould)[0]==10 and silver()==before
        expected=(sum(levels.needed(mould,n) for n in range(1,10))+value-1)//value
        quantity=db._conn.execute('SELECT quantity FROM local_inventory WHERE conta_id=? AND mould=?',(account,prop)).fetchone()[0]
        assert quantity==10000-expected
        assert request('ship_escalate',0,ship,food_text,10,'ninja-fast',seq='7').split(' ',1)[1]==reply.split(' ',1)[1]
        assert db._conn.execute('SELECT quantity FROM local_inventory WHERE conta_id=? AND mould=?',(account,prop)).fetchone()[0]==quantity
        assert ' -1 ' in request('ship_escalate',0,ship,food_text,101,'ninja-cap')
        assert ' -1 ' in request('ship_escalate',0,ship,str(instance)+':0',11,'zero')
        with db._conn:db._conn.execute('UPDATE local_campaign SET grade=10 WHERE conta_id=?',(account,))
        assert 'nivel_maximo_do_personagem' in request('ship_escalate',0,ship,str(instance)+':1',11,'at-cap')
        assert db._conn.execute('SELECT quantity FROM local_inventory WHERE conta_id=? AND mould=?',(account,prop)).fetchone()[0]==quantity
        for _ in range(4):assert ' -3 nao_implementado' in request('unimplemented_upgrade')
        info=equipment.equip_info(db,account,ship,mould)
        assert info in server.resposta_login_init('8','')
        # Close/reopen the connection and replay persisted receipts.
        import sqlite3
        path=db.caminho;db._conn.close();db._conn=sqlite3.connect(path,check_same_thread=False);db._conn.row_factory=sqlite3.Row
        assert equipment.equip_info(db,account,ship,mould)==info
        assert equip(1,10,'to-ten').startswith('2 equipment_escalate 0 ')
        assert db._conn.execute('PRAGMA integrity_check').fetchone()[0]=='ok'
        assert db._conn.execute('PRAGMA foreign_key_check').fetchall()==[]
        (root/'build/quick-equipment-reply.txt').write_text(quick,encoding='utf8')
        (root/'build/quick-ninja-reply.txt').write_text(reply,encoding='utf8')
        print('QUICK_UPGRADES_PASSED: exact costs, promotions, materials, balance, partial progress, caps, ownership, stats, login, durable replay, unsupported refusal')
    finally:db.fechar()
